def validate_auto_start(value):
    # `auto_start: true` is the compact form. Omitting auto_start preserves
    # pre-v0.1.9 behaviour for MQTT-only/legacy external-component users.
    if value is True:
        value = {}
    elif value is False:
        return False
    if not isinstance(value, dict):
        raise cv.Invalid("auto_start must be true, false, or a mapping")
    return AUTO_START_SCHEMA(value)


PLUGIN_SWITCHES_SCHEMA = cv.All(
    cv.ensure_list(validate_plugin_switch),
    cv.Length(min=1),
)


def validate_plugin_config(config):
    try:
        compiled = select_plugins(REPO, config[CONF_RX_PLUGINS], config[CONF_PLUGIN_PROFILE])
    except (OSError, ValueError) as error:
        raise cv.Invalid(str(error)) from error
    switches = config.get(CONF_PLUGIN_SWITCHES)
    if switches:
        ids = [entry[CONF_PLUGIN_NUMBER] for entry in switches]
        if len(ids) != len(set(ids)):
            raise cv.Invalid("plugin_switches contains duplicate plugin numbers")
        missing = sorted(set(ids) - set(compiled))
        if missing:
            raise cv.Invalid("Runtime switch requested for plugin(s) not compiled: " + ", ".join(f"{n:03d}" for n in missing))
    return config



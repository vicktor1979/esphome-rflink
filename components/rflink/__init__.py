def validate_plugin_switch(value):
    # v0.2.0.1 public syntax is intentionally just a list of plugin numbers:
    # plugin_switches: [30, 61, 254]
    # IDs, names and restore modes are generated by the component.
    if not (isinstance(value, int) or (isinstance(value, str) and value.strip().isdigit())):
        raise cv.Invalid("plugin_switches entries must be plugin numbers only, e.g. [30, 61, 254]")
    plugin_id = cv.int_range(min=1, max=255)(int(value))
    if plugin_id == 1:
        raise cv.Invalid("Plugin 001 is the RFLink packet preprocessor and is always enabled; do not list it.")
    return PLUGIN_SWITCH_SCHEMA({
        CONF_PLUGIN_NUMBER: plugin_id,
        CONF_NAME: f"RFLink {plugin_id:03d} · {PLUGIN_NAMES.get(plugin_id, 'Plugin')}",
    })


